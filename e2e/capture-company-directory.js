/**
 * Standalone screenshot capture script for the public Company Directory.
 * No login required — every page hit here is visible to an anonymous visitor.
 *
 * Captures 3 screenshots walking: full directory -> sector filter -> company
 * profile with the Subscriber Intelligence upsell card visible.
 *
 * Usage: node e2e/capture-company-directory.js
 *
 * @author  Bill Blackmon
 * @since   2026-11-22
 * @updated 2026-11-22
 */

const { chromium } = require('@playwright/test');
const path = require('path');
const fs   = require('fs');

try { require('dotenv').config(); } catch (_) {}

const BASE_URL = process.env.BASE_URL || 'https://app.bigskylabs.ai';
const SECTOR   = 'Medical Imaging & Diagnostics';

const TODAY = new Date().toLocaleDateString('en-CA'); // ISO YYYY-MM-DD

const SHOTS_DIR = path.resolve(__dirname, '../linkedin-posts/shots');
const TEXT_DIR  = path.resolve(__dirname, '../linkedin-posts/text');

(async () => {
    const browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    const page    = await context.newPage();

    // ── Step 1: Full directory, default Relevance sort, all sectors ──────────
    console.log(`[Step 1] Directory overview (${BASE_URL}/directory)`);
    await page.goto(`${BASE_URL}/directory`, { waitUntil: 'networkidle', timeout: 30_000 });
    await page.waitForTimeout(1000);

    const totalCountText = await page.locator('text=companies tracked by our AI discovery pipeline').first().innerText();
    console.log(`  ${totalCountText.trim()}`);

    const shot1 = path.join(SHOTS_DIR, `${TODAY}-company-directory-overview.png`);
    await page.screenshot({ path: shot1 }); // viewport only — fullPage produces a 5000px+ tall strip unsuitable for LinkedIn
    console.log(`  Saved -> ${path.basename(shot1)}\n`);

    // ── Step 2: Filter to one sector via the real pill link ──────────────────
    console.log(`[Step 2] Sector filter: ${SECTOR}`);
    await page.getByRole('link', { name: SECTOR, exact: true }).click();
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(800);

    const filteredCardCount = await page.locator('a:has-text("View profile")').count();
    console.log(`  ${filteredCardCount} companies in sector`);

    const shot2 = path.join(SHOTS_DIR, `${TODAY}-company-directory-sector-filter.png`);
    await page.screenshot({ path: shot2, fullPage: true });
    console.log(`  Saved -> ${path.basename(shot2)}\n`);

    // ── Step 3: Open the first company profile in that sector ────────────────
    console.log('[Step 3] Opening first company profile in sector');
    const firstProfileLink = page.locator('a:has-text("View profile")').first();
    const companyName = await firstProfileLink
        .locator('xpath=../..//a[contains(@class,"font-display")]')
        .first()
        .innerText()
        .catch(() => '(name not extracted)');
    await firstProfileLink.click();
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(800);
    console.log(`  Company: ${companyName.trim()}`);
    console.log(`  URL: ${page.url()}`);

    const shot3 = path.join(SHOTS_DIR, `${TODAY}-company-directory-profile.png`);
    await page.screenshot({ path: shot3, fullPage: true });
    console.log(`  Saved -> ${path.basename(shot3)}\n`);

    await browser.close();

    // ── Write a short post-ready text snippet ─────────────────────────────────
    const outputText = `=== COMPANY DIRECTORY DEMO — ${TODAY} ===
Generated by: node e2e/capture-company-directory.js

${totalCountText.trim()}
Sector filter demoed: ${SECTOR} (${filteredCardCount} companies)
Profile opened: ${companyName.trim()} — ${page.url()}

== SCREENSHOTS ==
1. ${path.basename(shot1)} — full directory, default Relevance sort
2. ${path.basename(shot2)} — filtered to "${SECTOR}"
3. ${path.basename(shot3)} — company profile with Subscriber Intelligence upsell visible

== NOTES ==
Everything above renders with zero login — this is what any anonymous visitor
sees today at ${BASE_URL}/directory. No AI calls were made to produce this demo
(the directory data and company write-ups were already generated by the nightly
discovery pipeline).
`;

    const textFile = path.join(TEXT_DIR, `${TODAY}-company-directory-demo.txt`);
    fs.writeFileSync(textFile, outputText, 'utf8');
    console.log(`Written -> ${path.basename(textFile)}`);
    console.log('\n=== Done ===');
})();
